"""Pack Blender swamp actions, level their bearing contours and bake contact lookup."""
import argparse
import hashlib
import json
import math
from pathlib import Path

import numpy as np
from PIL import Image

SOURCE_W, SOURCE_H = 240, 236
CELL_W, CELL_H = 176, 184
AX, AY = 88, 159
COLUMNS = 8
COUNT = 16


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def footprint(alpha, left, right):
    """Select an actual contiguous patch in the locally deepest two rows."""
    band = alpha[:,left:right] >= 92
    ys,xs = np.nonzero(band)
    if not len(xs):
        return None
    bottom = int(ys.max())
    bearing = np.any(band[max(0,bottom-2):bottom+1], axis=0)
    segments = np.split(np.flatnonzero(bearing), np.where(np.diff(np.flatnonzero(bearing)) > 1)[0]+1)
    best = max(segments,key=len)
    center = int(best[len(best)//2])
    return (left+center+.5-AX, float(np.flatnonzero(band[:,center])[-1])+.5-AY,
            min(11,max(1.5,len(best)*.58)))


def write_light_core(root):
    """Track the brightest connected part of the yellow-green lantern in each pose."""
    atlas = root/"assets/media/mokradla-ruch/actor-2.png"
    yy, xx = np.indices((CELL_H, CELL_W))
    lines = ["#pragma once", "// Generated by marsh_actor_pack.py. Positions are relative to the sprite anchor.",
             "namespace marsh_actor_frames {", "struct Core {float x,y;};",
             "inline constexpr Core LightCore[4][16]={"]
    with Image.open(atlas) as image:
        for clip in range(4):
            entries = []
            for frame in range(COUNT):
                index = clip*COUNT+frame
                x0, y0 = index%COLUMNS*CELL_W, index//COLUMNS*CELL_H
                rgba = np.asarray(image.crop((x0,y0,x0+CELL_W,y0+CELL_H)), dtype=float)
                red, green, blue, alpha = rgba.transpose(2,0,1)
                light = (.35*red+.65*green-.45*blue)*alpha/255
                py, px = np.unravel_index(light.argmax(),light.shape)
                # Falloff isolates the luminous heart from highlights on the reed husk.
                weight = np.maximum(0,light-light[py,px]+13)**2
                weight *= (xx-px)**2+(yy-py)**2 <= 15**2
                cx, cy = np.average(xx,weights=weight), np.average(yy,weights=weight)
                # The painted filament crosses a translucent slit. Keep the
                # emitter on a luminous pixel even when the centroid is in it.
                distance = np.where(weight > 0, (xx-cx)**2+(yy-cy)**2, np.inf)
                y, x = np.unravel_index(distance.argmin(),distance.shape)
                entries.append(f"{{{x+.5-AX:.2f}f,{y+.5-AY:.2f}f}}")
            lines.append("{"+",".join(entries)+"},")
    lines.extend(["};", "}", ""])
    (root/"src/generated/marsh_light_core.hpp").write_text("\n".join(lines),encoding="utf-8")


def export(source, root, reports):
    dest = root/"assets/media/mokradla-ruch"
    dest.mkdir(parents=True,exist_ok=True)
    packed=[];all_feet=[];heights=[];stats=[]
    for species in range(4):
        with Image.open(source/f"render-{species}.png") as im:
            sheet=im.convert("RGBA")
        assert sheet.size==(SOURCE_W*8,SOURCE_H*8)
        atlas=Image.new("RGBA",(COLUMNS*CELL_W,8*CELL_H))
        entries=[];min_border=CELL_W;worst_gap=0
        for index in range(64):
            sx=index%8*SOURCE_W;sy=index//8*SOURCE_H
            frame=sheet.crop((sx,sy,sx+SOURCE_W,sy+SOURCE_H))
            a=np.asarray(frame.getchannel("A"))
            ys,xs=np.nonzero(a>=40)
            bottom=np.where(a>=92)[0].max()
            if not index:heights.append(float(bottom-ys.min()+1))
            x_offset=int(np.clip(AX-SOURCE_W//2,2-xs.min(),CELL_W-3-xs.max()))
            y_offset=int(AY-bottom)
            result=frame.crop((-x_offset,-y_offset,CELL_W-x_offset,CELL_H-y_offset))
            x0,y0,x1,y1=xs.min()+x_offset,ys.min()+y_offset,xs.max()+x_offset,ys.max()+y_offset
            border=int(min(x0,CELL_W-1-x1,y0,CELL_H-1-y1))
            if border < 2:raise RuntimeError(f"Clipped {species} / {index}: {border}")
            min_border=min(min_border,border)
            alpha=np.asarray(result.getchannel("A"))
            width=x1-x0+1
            split=int(x0+width*(.54 if species==3 else .50))
            candidates=[footprint(alpha,int(x0),split),footprint(alpha,split,int(x1)+1)]
            assert all(foot is not None for foot in candidates)
            # A single trailing filament is the bearing point of the lantern. Do
            # not put ambient occlusion under its upper leaves or hovering tips.
            if species==2:
                candidates=[(x,y,0 if y < -9 else r) for x,y,r in candidates]
            nearest=max(y for _,y,r in candidates if r>0)
            worst_gap=max(worst_gap,abs(nearest-.5))
            assert nearest>=-1.5,(species,index,candidates)
            atlas.paste(result,(index%8*CELL_W,index//8*CELL_H))
            entries.append(candidates)
        all_feet.append(entries)
        stats.append(dict(species=species,minimum_cell_margin=min_border,max_contact_error_px=worst_gap))
        path=dest/f"actor-{species}.png";atlas.save(path,optimize=True)
        with Image.open(path) as check:
            assert check.size==atlas.size and check.mode=="RGBA" and check.tobytes()==atlas.tobytes()
        packed.append({"file":path.name,"bytes":path.stat().st_size,"sha256":sha(path)})
    write_light_core(root)
    lines=["#pragma once",'#include "marsh_light_core.hpp"', "// Generated by tools/media/marsh_actor_pack.py from the four Blender actions.",
           "namespace marsh_actor_frames {","enum Clip {Walk,Attack,Hurt,Death};",
           "inline constexpr int CellW=176,CellH=184,Columns=8,Frames=16;",
           "inline constexpr float AnchorX=88,AnchorY=159;",
           "inline constexpr float RestHeight[4]={"+",".join(f"{v:.1f}f" for v in heights)+"};",
           "struct Foot {float x,y,rx;};","inline constexpr Foot Supports[4][4][16][2]={"]
    for entries in all_feet:
        lines.append("{")
        for clip in range(4):
            lines.append("{")
            for row in entries[clip*16:clip*16+16]:
                lines.append("{"+",".join("{"+",".join(f"{n:.2f}f" for n in point)+"}" for point in row)+"},")
            lines.append("},")
        lines.append("},")
    lines+=["};","}",""]
    (root/"src/generated/marsh_actor_frames.hpp").write_text("\n".join(lines),encoding="utf-8")
    report={"source":"assets/media/mokradla/atlas.png","source_sha256":sha(root/"assets/media/mokradla/atlas.png"),
            "master":str(source/"Mokradla-bestie.blend"),"renderer":"Blender Cycles / painted 2D grids",
            "provenance":"Original Emberfall marsh atlas, locally articulated and rendered in Blender",
            "atlas_files":packed,"cell":[CELL_W,CELL_H],"ground_anchor":[AX,AY],"rest_height":heights,
            "actions":["walk","attack","hurt","death"],"frames_per_action":COUNT,
            "checks":stats,"render":json.loads((source/"render.json").read_text(encoding="utf-8"))}
    for path in [dest/"import-receipt.json",reports/"actors-export.json"]:
        path.write_text(json.dumps(report,indent=2,ensure_ascii=False)+"\n",encoding="utf-8")
    print(json.dumps(stats))


if __name__=="__main__":
    parser=argparse.ArgumentParser()
    parser.add_argument("--root",type=Path,required=True)
    parser.add_argument("--source",type=Path)
    parser.add_argument("--reports",type=Path)
    parser.add_argument("--light-core-only",action="store_true")
    params=parser.parse_args()
    if params.light_core_only:
        write_light_core(params.root)
    elif params.source and params.reports:
        export(params.source,params.root,params.reports)
    else:
        parser.error("Full export requires --source and --reports.")
